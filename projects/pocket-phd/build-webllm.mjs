// Install with npm ci --ignore-scripts; build never downloads models.
import { build } from 'esbuild';
import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const result = await build({
  entryPoints: ['node_modules/@mlc-ai/web-llm/lib/index.js'],
  outfile: 'vendor/web-llm.js', bundle: true, format: 'esm', platform: 'browser',
  target: 'es2022', minify: false, legalComments: 'inline', metafile: true,
  banner: {js: '// @mlc-ai/web-llm 0.2.80; generated by npm run build:vendor. See vendor/README.md.'}
});
const output = result.metafile.outputs['vendor/web-llm.js'];
if (output.imports.length) throw new Error('Unexpected external runtime imports');
for (const name of ['CreateWebWorkerMLCEngine', 'WebWorkerMLCEngineHandler']) {
  if (!output.exports.includes(name)) throw new Error(`Missing export: ${name}`);
}
await mkdir('vendor/licenses', { recursive: true });
await copyFile('node_modules/@mlc-ai/web-llm/LICENSE', 'vendor/licenses/web-llm-Apache-2.0.txt');
await copyFile('node_modules/loglevel/LICENSE-MIT', 'vendor/licenses/loglevel-MIT.txt');
// Preserve upstream license and attribution comments verbatim, including notices
// that esbuild does not classify as legalComments because they use plain /*.
const upstream = await readFile('node_modules/@mlc-ai/web-llm/lib/index.js', 'utf8');
const notices = [...upstream.matchAll(/\/\*[\s\S]*?\*\//g)]
  .map(match => match[0]).filter(comment => /copyright|licens|permission is hereby granted/i.test(comment));
await writeFile('vendor/licenses/upstream-notices.txt', [...new Set(notices)].join('\n\n') + '\n');
const bundle = await readFile('vendor/web-llm.js');
await writeFile('vendor/build-manifest.json', JSON.stringify({
  package: '@mlc-ai/web-llm', version: '0.2.80', esbuild: '0.25.12',
  bytes: bundle.length, sha256: createHash('sha256').update(bundle).digest('hex'),
  imports: output.imports, exports: output.exports,
  inputs: Object.keys(result.metafile.inputs).sort()
}, null, 2) + '\n');
console.log(`Verified ${bundle.length} bytes; no external JS imports; worker exports present.`);
