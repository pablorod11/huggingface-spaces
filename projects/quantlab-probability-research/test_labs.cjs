const assert = require('node:assert/strict');
const labs = require('./labs.js');
const vm = require('node:vm');
const fs = require('node:fs');
const workerContext = vm.createContext({TextEncoder});
vm.runInContext(fs.readFileSync(require.resolve('./labs.js'), 'utf8'), workerContext);
assert.equal(typeof workerContext.QuantLabs?.parseCSV, 'function', 'Worker global must expose QuantLabs without window');
const pd = labs.game('prisoner');
assert.deepEqual(pd.pureNash, [[1, 1]]);
assert.deepEqual(pd.strictDominantRows, [1]);
assert.deepEqual(labs.game('matching'), {name:'Matching pennies', rowPayoffs:[[1,-1],[-1,1]],columnPayoffs:[[-1,1],[1,-1]],pureNash:[],mixed:{rowProbability:.5,columnProbability:.5,value:0}});
assert.throws(() => labs.game('unknown'));
const bs = labs.blackScholes(100,100,1,.05,.2);
assert.ok(Math.abs(bs.call-10.450583572185565)<1e-5);
assert.ok(Math.abs(bs.call-bs.put-(100-100*Math.exp(-.05)))<1e-10);
assert.throws(() => labs.blackScholes(0,100,1,.05,.2));
assert.ok(Math.abs(labs.kelly(.6,1)-.05)<1e-12);
assert.equal(labs.kelly(.1,1),0);
assert.equal(labs.kelly(1,1,1,.25),.25);
assert.throws(() => labs.kelly(1.1,1));
const d=labs.diagnostics([100,110,99,105]);
assert.equal(d.n,3);
assert.ok(Math.abs(d.mean-Math.log(1.05)/3)<1e-12);
assert.ok(Number.isFinite(d.skew));
assert.match(d.normality_note,/not independence/);
assert.throws(() => labs.diagnostics([100,0,110]));
function csv(n=714) {
 let lines=['date,close,note'];
 for(let i=0;i<n;i++) lines.push(`${new Date(Date.UTC(2020,0,1+i)).toISOString().slice(0,10)},${100+i},"quoted, value ""ok"""`);
 return lines.join('\r\n');
}
let parsed=labs.parseCSV(csv());
assert.equal(parsed.closes.length,714);
assert.equal(parsed.calendarGapMaxDays,1);
assert.throws(()=>labs.parseCSV(csv(713)));
assert.throws(()=>labs.parseCSV(csv(2501)));
assert.throws(()=>labs.parseCSV(csv().replace('2020-01-02','2020-01-01')));
assert.throws(()=>labs.parseCSV(csv().replace('2020-01-02','2020-02-30')));
assert.throws(()=>labs.parseCSV(csv().replace(',101,',',-1,')));
assert.throws(()=>labs.parseCSV(csv().replace(',101,',',NaN,')));
assert.throws(()=>labs.parseCSV(csv().replace('date,close,note','date,close,close')));
assert.throws(()=>labs.parseCSV(csv()+'\n"unterminated'));
assert.throws(()=>labs.parseCSV(csv().replace('"quoted, value ""ok"""','"a"oops')));
assert.throws(()=>labs.parseCSV('x'.repeat(2*1024*1024+1)));
assert.equal(labs.parseCSV(csv().replace('"quoted, value ""ok"""','"multi\nline"')).closes.length,714);
console.log('labs tests passed (games, pricing, sizing, moments, CSV validation)');
