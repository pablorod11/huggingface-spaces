const assert=require('node:assert/strict');
const labs=require('./labs.js');
const rows=Array.from({length:714},(_,i)=>`${new Date(Date.UTC(2020,0,1+i)).toISOString().slice(0,10)},${100+i/100}`);
const csv='date,close\n'+rows.join('\n');
const clean=labs.parseCSV('\uFEFF Date , CLOSE \r\n'+rows.map(r=>r.split(',').map(v=>' '+v+' ').join(',')).join('\r\n'));
assert.equal(clean.closes.length,714);
assert.equal(clean.quality.normalizedHeaderFields,2);
assert.equal(clean.quality.trimmedValues,1428);
assert.equal(clean.quality.bomRemoved,true);
assert.equal(clean.quality.rowsDropped,0);
assert.equal(clean.quality.imputedValues,0);
assert.deepEqual(clean.closes,labs.parseCSV(csv).closes);
assert.throws(()=>labs.parseCSV(csv.replace('date,close','date,close, Close ')),/Duplicate/);
assert.throws(()=>labs.parseCSV(csv.replace(rows[1],rows[0])),/row 3.*unique/i);
assert.throws(()=>labs.parseCSV(csv.replace(rows[1],rows[1].split(',')[0]+',')),/row 3.*missing/i);
assert.throws(()=>labs.parseCSV(csv.replace('100.01','0x100')),/row 3.*numeric/i);
assert.throws(()=>labs.parseCSV('date,close\n'+(','.repeat(65))),/64 columns/);
assert.throws(()=>labs.parseCSV('date,close\n'+('x'.repeat(16385))),/16384 characters/);
assert.throws(()=>labs.parseCSV('date,close\n'+('a,b\n'.repeat(2502))),/2500 price rows/);
const jump=labs.parseCSV(csv.replace(rows[1],rows[1].split(',')[0]+',200'));
assert.equal(jump.quality.largeMoveCount,2);
const exactThreshold=labs.parseCSV(csv.replace('100.01','120'));assert.equal(exactThreshold.quality.largeMoveCount,1,'Exactly +20% must be flagged; the following drop is less than 20%');
assert.equal(jump.closes[1],200,'Large returns must be flagged, never silently clipped');
assert.equal(jump.quality.rowsDropped,0);
assert.equal(labs.parseCSV(csv.replace(rows[1],rows[1].split(',')[0]+',1e300')).quality.largeMoveCount,2);
assert.throws(()=>labs.parseCSV(csv.replace(rows[1],rows[1].split(',')[0]+',Infinity')),/finite|numeric/);
console.log('Data quality tests passed: transparent normalization, strict chronology, bounded parser, retained outliers');
